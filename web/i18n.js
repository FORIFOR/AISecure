function initialLang() {
  if (typeof window !== 'undefined' && (window.__AI_SECURE_LANG__ === 'ja' || window.__AI_SECURE_LANG__ === 'en')) return window.__AI_SECURE_LANG__;
  try { const saved = localStorage.getItem('ai-secure-lang'); if (saved === 'ja' || saved === 'en') return saved; } catch (e) {}
  return (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'en';
}
let lang = initialLang();

function t(key, ...args) {
  const dict = I18N[lang] || I18N.en;
  const v = key in dict ? dict[key] : I18N.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}

function applyStatic(root) {
  (root || document).querySelectorAll('[data-i18n]').forEach(node => {
    const v = t(node.dataset.i18n);
    if (node.dataset.i18nHtml !== undefined) node.innerHTML = v; else node.textContent = v;
  });
  document.documentElement.lang = lang;
}

function setLang(next) {
  lang = (next === 'ja') ? 'ja' : 'en';
  try { localStorage.setItem('ai-secure-lang', lang); } catch (e) {}
}
